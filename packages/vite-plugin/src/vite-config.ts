import {
	defaultClientConditions,
	defaultClientMainFields,
	defaultServerConditions,
	defaultServerMainFields,
	searchForWorkspaceRoot,
	type EnvironmentOptions,
	type UserConfig
} from 'vite';
import {
	crawlFrameworkPkgs,
	isDepExcluded,
	isDepExternaled,
	isDepIncluded,
	isDepNoExternaled,
	type CrawlFrameworkPkgsResult
} from 'vitefu';
import { shipsNoSources } from './dependencies.ts';
import type { FrontEnd } from './front-end.ts';
import { log } from './log.ts';
import type { PreResolvedOptions } from './options.ts';

const missingConditionLink =
	'https://github.com/sveltejs/vite-plugin-svelte/blob/main/docs/faq.md#missing-exports-condition';

interface Lists {
	optimizeDeps: { include: string[]; exclude: string[] };
	ssr: { noExternal: (string | RegExp)[]; external: string[] };
}

export function deduped(frontEnd: FrontEnd): string[] {
	return frontEnd.imports.filter((name) => name !== frontEnd.compilerImport);
}

function clientImports(frontEnd: FrontEnd): string[] {
	return deduped(frontEnd).filter(
		(name) => !name.endsWith('/server') && !name.includes('/server/')
	);
}

function escape(text: string): string {
	return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function frontEndLists(config: UserConfig, frontEnds: readonly FrontEnd[]): Lists {
	const include: string[] = [];
	const noExternal: (string | RegExp)[] = [];
	for (const frontEnd of frontEnds) {
		if (!isDepExcluded(frontEnd.name, config.optimizeDeps?.exclude ?? [])) {
			const imports = clientImports(frontEnd);
			log.debug(
				`adding bare ${frontEnd.name} packages to optimizeDeps.include: ${imports.join(', ')} `,
				undefined,
				'config'
			);
			include.push(...imports);
		} else {
			log.debug(
				`"${frontEnd.name}" is excluded in optimizeDeps.exclude, skipped adding it to include.`,
				undefined,
				'config'
			);
		}
		if (!isDepExternaled(frontEnd.name, config.ssr?.external ?? [])) {
			noExternal.push(frontEnd.name, new RegExp(`^${escape(frontEnd.name)}\\/`));
		}
	}
	if (!isDepExternaled('esm-env', config.ssr?.external ?? [])) noExternal.push('esm-env');
	return { optimizeDeps: { include, exclude: [] }, ssr: { noExternal, external: [] } };
}

function hasCondition(exports: unknown, conditions: readonly string[]): boolean {
	if (exports === null || typeof exports !== 'object') return false;
	let found = false;
	JSON.stringify(exports, (key, value) => {
		if (conditions.includes(key)) found = true;
		return value;
	});
	return found;
}

async function dependencyLists(
	options: PreResolvedOptions,
	config: UserConfig,
	frontEnds: readonly FrontEnd[]
): Promise<CrawlFrameworkPkgsResult> {
	const conditions = frontEnds.map((frontEnd) => frontEnd.condition);
	const names = new Set(frontEnds.map((frontEnd) => frontEnd.name));
	const withoutCondition = new Set<string>();
	const lists = await crawlFrameworkPkgs({
		root: options.root,
		workspaceRoot: searchForWorkspaceRoot(options.root),
		isBuild: options.isBuild,
		viteUserConfig: config,
		isFrameworkPkgByJson(manifest) {
			const condition = hasCondition(manifest.exports, conditions);
			const field = conditions.some((name) => !!manifest[name]);
			if (field && !condition) withoutCondition.add(`${manifest.name}@${manifest.version}`);
			return condition || field;
		},
		isSemiFrameworkPkgByJson(manifest) {
			return [...names].some(
				(name) => !!manifest.dependencies?.[name] || !!manifest.peerDependencies?.[name]
			);
		},
		isFrameworkPkgByName(name) {
			return names.has(name) || shipsNoSources(name) ? false : undefined;
		}
	});
	if (
		!options.isBuild &&
		!options.experimental?.disableSvelteResolveWarnings &&
		withoutCondition.size > 0
	) {
		log.info.once(
			`The following packages have a svelte field in their package.json but no exports condition for svelte.\n\n${[...withoutCondition].join('\n')}\n\nPlease see ${missingConditionLink} for details.`
		);
	}
	log.debug('extra config for dependencies generated by vitefu', lists, 'config');
	if (options.prebundleSvelteLibraries) {
		lists.optimizeDeps.exclude = [];
		const excluded = config.optimizeDeps?.exclude;
		lists.optimizeDeps.include = !excluded
			? []
			: lists.optimizeDeps.include.filter(
					(dep) =>
						dep.includes('>') &&
						dep
							.split('>')
							.slice(0, -1)
							.some((part) => isDepExcluded(part.trim(), excluded))
				);
	}
	const disabled = options.disableDependencyReinclusion;
	if (disabled === true) {
		lists.optimizeDeps.include = lists.optimizeDeps.include.filter((dep) => !dep.includes('>'));
	} else if (Array.isArray(disabled)) {
		lists.optimizeDeps.include = lists.optimizeDeps.include.filter((dep) => {
			if (!dep.includes('>')) return true;
			const trimmed = dep.replace(/\s+/g, '');
			return disabled.some((name) => trimmed.includes(`${name}>`));
		});
	}
	log.debug('post-processed extra config for dependencies', lists, 'config');
	return lists;
}

function validateViteConfig(
	extra: UserConfig,
	config: UserConfig,
	options: PreResolvedOptions
): void {
	const { prebundleSvelteLibraries, isBuild } = options;
	if (prebundleSvelteLibraries) {
		const enabled = (option: 'dev' | 'build' | boolean) =>
			option !== true && option !== (isBuild ? 'build' : 'dev');
		const warn = (name: string, value: unknown, recommendation: string) =>
			log.warn.once(
				`Incompatible options: \`prebundleSvelteLibraries: true\` and vite \`${name}: ${JSON.stringify(value)}\` ${isBuild ? 'during build.' : '.'} ${recommendation}`
			);
		const disabled = config.optimizeDeps?.disabled ?? 'build';
		const optimizing = enabled(disabled);
		if (!isBuild && !optimizing) {
			warn(
				'optimizeDeps.disabled',
				disabled,
				'Forcing `optimizeDeps.disabled: "build"`. Disable prebundleSvelteLibraries or update your vite config to enable optimizeDeps during dev.'
			);
			extra.optimizeDeps ??= {};
			extra.optimizeDeps.disabled = 'build';
		} else if (isBuild && optimizing) {
			warn(
				'optimizeDeps.disabled',
				disabled,
				'Disable optimizeDeps or prebundleSvelteLibraries for build if you experience errors.'
			);
		}
	}
	if (isBuild) {
		type Optimization = { optimization?: { inlineConst?: boolean } };
		const build = config.build as
			| { rolldownOptions?: Optimization; rollupOptions?: Optimization }
			| undefined;
		const inlineConst =
			build?.rolldownOptions?.optimization?.inlineConst ??
			build?.rollupOptions?.optimization?.inlineConst;
		if (inlineConst === false) {
			log.warn(
				'Your rolldown config contains `optimization.inlineConst: false`. This can lead to increased bundle size and leaked server code in client build.'
			);
		}
	}
}

export async function buildExtraViteConfig(
	options: PreResolvedOptions,
	config: UserConfig,
	frontEnds: readonly FrontEnd[]
): Promise<UserConfig> {
	const extra: UserConfig = { resolve: { dedupe: frontEnds.flatMap(deduped) } };
	const own = frontEndLists(config, frontEnds);
	const deps = await dependencyLists(options, config, frontEnds);
	extra.optimizeDeps = {
		include: [
			...own.optimizeDeps.include,
			...deps.optimizeDeps.include.filter((dep) => !isDepExcluded(dep, own.optimizeDeps.exclude))
		],
		exclude: [
			...own.optimizeDeps.exclude,
			...deps.optimizeDeps.exclude.filter((dep) => !isDepIncluded(dep, own.optimizeDeps.include))
		]
	};
	extra.ssr = {
		external: [
			...own.ssr.external,
			...deps.ssr.external.filter((dep) => !isDepNoExternaled(dep, own.ssr.noExternal))
		],
		noExternal: [
			...own.ssr.noExternal,
			...deps.ssr.noExternal.filter((dep) => !isDepExternaled(dep, own.ssr.external))
		]
	};
	if (config.experimental?.hmrPartialAccept !== false) {
		log.debug('enabling "experimental.hmrPartialAccept" in vite config', undefined, 'config');
		extra.experimental = { hmrPartialAccept: true };
	}
	validateViteConfig(extra, config, options);
	return extra;
}

function client(
	name: string,
	config: EnvironmentOptions,
	opts: { isSsrTargetWebworker?: boolean }
) {
	return config.consumer === 'client' || name === 'client' || !!opts.isSsrTargetWebworker;
}

export function ensureEnvironmentResolve(
	name: string,
	config: EnvironmentOptions,
	opts: { isSsrTargetWebworker?: boolean }
): { mainFields: string[]; conditions: string[] } {
	config.resolve ??= {};
	const onClient = client(name, config, opts);
	config.resolve.mainFields ??= [...(onClient ? defaultClientMainFields : defaultServerMainFields)];
	config.resolve.conditions ??= [...(onClient ? defaultClientConditions : defaultServerConditions)];
	return config.resolve as { mainFields: string[]; conditions: string[] };
}
