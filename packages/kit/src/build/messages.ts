import { throwDiagnostic, warnDiagnostic } from '../shared/diagnostics.ts';

interface InstrumentationMessage {
	kind: string;
	file: string;
}
interface FileMessage {
	file: string;
}
interface RouteMessage {
	id: string;
}
interface NameMessage {
	name: string;
}
interface HashMessage {
	file: string;
	options: string;
}
export function adapter_generate_manifest_removed(): never {
	throwDiagnostic(
		'adapter_generate_manifest_removed',
		'`builder.generateManifest` has been removed. Use `builder.generateServerInstance` instead.',
		adapter_generate_manifest_removed
	);
}
export function adapter_instrumentation_file_missing({
	kind,
	file
}: InstrumentationMessage): never {
	throwDiagnostic(
		'adapter_instrumentation_file_missing',
		`${kind} not found at \`${file}\``,
		adapter_instrumentation_file_missing
	);
}
export function adapter_fallback_overwrites({ file }: FileMessage): void {
	warnDiagnostic(
		'adapter_fallback_overwrites',
		`Overwriting \`${file}\` with fallback page. Consider using a different name for the fallback.`
	);
}
export function router_hash_page_options({ file, options }: HashMessage): never {
	throwDiagnostic(
		'router_hash_page_options',
		`Page options ${options} cannot be used with hash routing in ${file}`,
		router_hash_page_options
	);
}
export function params_export_missing(): never {
	throwDiagnostic(
		'params_export_missing',
		'The params module does not export params from defineParams',
		params_export_missing
	);
}
export function param_matcher_missing({ name }: NameMessage): never {
	throwDiagnostic(
		'param_matcher_missing',
		`No matcher found for parameter \`${name}\``,
		param_matcher_missing
	);
}
export function prerender_actions({ id }: RouteMessage): never {
	throwDiagnostic(
		'prerender_actions',
		`Cannot prerender a page with actions (${id})`,
		prerender_actions
	);
}
export function prerender_endpoint_methods({ id }: RouteMessage): never {
	throwDiagnostic(
		'prerender_endpoint_methods',
		`Cannot prerender endpoint ${id} with body-dependent methods`,
		prerender_endpoint_methods
	);
}
export function route_prerender_page_and_endpoint({ id }: RouteMessage): never {
	throwDiagnostic(
		'route_prerender_page_and_endpoint',
		`Cannot prerender both the page and endpoint for ${id}`,
		route_prerender_page_and_endpoint
	);
}
export function route_config_mismatch({ id }: RouteMessage): never {
	throwDiagnostic(
		'route_config_mismatch',
		`Page and endpoint config must match for ${id}`,
		route_config_mismatch
	);
}
export function remote_export_invalid({ name }: NameMessage): never {
	throwDiagnostic('remote_export_invalid', `Invalid remote export ${name}`, remote_export_invalid);
}
export function prerender_http_error(
	status: number,
	path: string,
	referrer: string | null,
	referenceType: string
): string {
	return `prerender_http_error\n${status} ${path}${referrer ? ` (${referenceType} from ${referrer})` : ''}\nhttps://svelte.dev/e/kit/prerender_http_error`;
}
export function prerender_invalid_url(href: string, referrer: string | null): string {
	return `prerender_invalid_url\nInvalid URL ${href}${referrer ? ` linked from ${referrer}` : ''}\nhttps://svelte.dev/e/kit/prerender_invalid_url`;
}
export function prerender_missing_id(path: string, id: string, referrers: string[]): string {
	return `prerender_missing_id\nMissing id ${id} on ${path}, linked from ${referrers.join(', ')}\nhttps://svelte.dev/e/kit/prerender_missing_id`;
}
export function prerender_entry_generator_mismatch(
	id: string,
	entry: string,
	matched: string
): string {
	return `prerender_entry_generator_mismatch\nEntry ${entry} generated by ${id} matched ${matched}\nhttps://svelte.dev/e/kit/prerender_entry_generator_mismatch`;
}
export function prerender_unseen_routes(routes: string[]): string {
	return `prerender_unseen_routes\nThe following routes were marked as prerenderable but were not prerendered: ${routes.join(', ')}\nhttps://svelte.dev/e/kit/prerender_unseen_routes`;
}
export function prerender_client_address(): never {
	throwDiagnostic(
		'prerender_client_address',
		'Cannot read client address while prerendering',
		prerender_client_address
	);
}
export function prerender_fallback_failed(): never {
	throwDiagnostic(
		'prerender_fallback_failed',
		'Could not generate a fallback page',
		prerender_fallback_failed
	);
}
